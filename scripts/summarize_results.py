"""Generate docs/RESULTS.md from run outputs (no hand-copied numbers).

usage: python scripts/summarize_results.py [outputs/<run> ...]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = {
    "hilti_floor_2_2025-12-03_run_1": ("development", "configs/hilti_floor2_1203.yaml",
                                       "floor 2, static init, normal light; used for development and parameter selection"),
    "hilti_floor_2_2025-10-28_run_2": ("held-out #1", "configs/hilti_floor2_1028_run2.yaml",
                                       "floor 2, low light + clutter + aggressive motion; exposed generic bugs (jump rule, lost-gap handling) that were fixed; no parameter tuning"),
    "hilti_floor_1_2025-05-05_run_1": ("held-out #2", "configs/hilti_floor1_0505.yaml",
                                       "floor 1 (different plan), early construction phase; untouched during development"),
}


def j(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def f(v, nd=2, pct=False):
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int,)) and not isinstance(v, bool):
        return str(v)
    try:
        return f"{100 * v:.0f}%" if pct else f"{v:.{nd}f}"
    except (TypeError, ValueError):
        return str(v)


def main(runs):
    L = ["# Results", "",
         "Generated by `python scripts/summarize_results.py` from `outputs/<run>/` files. Every number below is read from those files.", "",
         "**Conditions common to all runs**",
         "- Input: Hilti-Trimble-Oxford 2026 dual-fisheye bags, stitched by slam3d to 1920×960 equirect.",
         "- SLAM: monocular equirect stella_vslam. The IMU is used for gravity and as a coarse scale prior, not in tracking.",
         "- Ground truth (LiDAR, plan frame) is used **only** for evaluation, except the `known_start` experiments, whose start pose comes from the challenge's `init_gt_poses.csv` as allowed by its localization track.",
         "- PF parameters and the segment-refinement window were selected on the development sequence and used unchanged on the held-out runs.",
         "- Machine: RTX 5070 Laptop 8 GB, 24 threads, 31 GB RAM.", ""]
    L += ["## Summary", "", "| run | role | video s | processing s (ratio) | SLAM tracked | ATE Sim3 final / online m | plan-frame 2D median / RMSE m | Hilti score (rule / uncapped) | PF known start median m (<1 m) | PF global converged s |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    details = []
    for rd in runs:
        name = rd.name
        role, cfg, desc = ROLES.get(name, ("other", "?", ""))
        rep = j(rd / "report.json") or {}
        geo = j(rd / "geometry/geometry.json") or {}
        ge = j(rd / "geometry/eval.json") or {}
        al = j(rd / "align/alignment.json") or {}
        ae = j(rd / "align/eval.json") or {}
        dr = j(rd / "dense/dense_report.json") or {}
        dc = j(rd / "discrepancy/discrepancies.json") or {}
        ob = j(rd / "objects/objects_report.json") or {}
        vv = j(rd / "viewer/validation.json") or {}
        loc = {p.parent.name: j(p) for p in sorted((rd / "localize").glob("*/pf_report.json")) if not p.parent.name.startswith("_")}
        tr = geo.get("tracking", {})
        fcsv = rd / "ingest/frames.csv"
        t_first = float(fcsv.read_text().splitlines()[1].split(",")[1]) if fcsv.exists() else 0.0
        lost = [f"{a - t_first:.1f}–{b - t_first:.1f} s" for a, b, _n in tr.get("lost_segments_after_init", [])]
        refined = ae.get("plan_frame_2d_error_no_extra_alignment", {})
        filled = ae.get("filled_trajectory_2d", {})
        ks = (loc.get("known_start") or {}).get("evaluation_vs_gt", {})
        gi = (loc.get("global_init") or {}).get("evaluation_vs_gt", {})
        L.append(f"| {name} | {role} | {f(rep.get('video_duration_s'), 1)} | {f(rep.get('processing_time_s'), 0)} ({f(rep.get('processing_to_video_ratio'), 2)}×) | "
                 f"{f(tr.get('tracked_frac'), pct=True)} | {f(ge.get('slam_ate_sim3', {}).get('rmse'))} / {f(ge.get('online_ate_sim3', {}).get('rmse'))} | "
                 f"{f(refined.get('median'))} / {f(refined.get('rmse'))} | {f(filled.get('hilti_score'), 1)} / {f(filled.get('hilti_score_ignoring_coverage_rule'), 1)} | "
                 f"{f(ks.get('err_median_m'))} ({f(ks.get('frac_below_1m'), pct=True)}) | {f(gi.get('converged_below_1m_at_s'), 1)} |")

        D = [f"## {name} ({role})", "", f"{desc}. Reproduce: `slam3d run {cfg}`.", ""]
        D += ["### Runtime (measured by the stage runner)", "", "| stage | runtime s | peak RSS MB | peak GPU (device) MB | peak docker MB |", "|---|---|---|---|---|"]
        for k, v in (rep.get("stages") or {}).items():
            D.append(f"| {k} | {f(v.get('runtime_s'), 1)} | {f(v.get('peak_rss_mb'), 0)} | {f(v.get('peak_gpu_used_mb'), 0)} | {f(v.get('peak_docker_mem_mb'), 0)} |")
        D.append(f"\nVideo {f(rep.get('video_duration_s'), 1)} s, {rep.get('n_frames')} frames; sum of stage runtimes {f(rep.get('processing_time_s'), 0)} s. "
                 "Some stages were re-run during development; the table shows the latest run of each stage.")
        sc = geo.get("scale", {})
        gt_s = ge.get("slam_ate_sim3", {}).get("scale")
        imu = sc.get("imu", {}) or {}
        D += ["", "### SLAM and geometry", "",
              f"- Tracked {f(tr.get('tracked_frac'), pct=True)} of frames ({f(tr.get('tracked_frac_after_init'), pct=True)} after init). Init after {f(tr.get('init_time_s'), 1)} s. Lost segments: {', '.join(lost) if lost else 'none'}.",
              f"- Tracking time {f(tr.get('track_ms_median'), 1)} ms median / {f(tr.get('track_ms_p95'), 1)} ms p95 per frame.",
              f"- {geo.get('n_keyframes')} keyframes, {geo.get('n_landmarks')} landmarks. Keyframe reprojection {f(geo.get('reprojection', {}).get('angle_deg_median'), 3)}° median, {f(geo.get('reprojection', {}).get('angle_deg_p90'), 3)}° p90.",
              f"- Low-parallax sections: {', '.join(f'{a - t_first:.1f}–{b - t_first:.1f} s' for a, b, _n in geo.get('low_parallax_sections', [])) or 'none'}.",
              f"- Gravity: {geo.get('gravity', {}).get('method')} (spread {f(geo.get('gravity', {}).get('angular_spread_deg_median'))}° median).",
              f"- Scale sources vs GT Sim3 scale ({f(gt_s, 4)} m/unit):",
              f"  - IMU second-difference identity {f(imu.get('metres_per_unit', 0) / gt_s if gt_s and imu.get('metres_per_unit') else None, 3)}× (corr {f(imu.get('corr'), 3)}, lag {imu.get('lag_s')} s);",
              f"  - camera-height prior {f(sc.get('camera_height_prior', {}).get('metres_per_unit', 0) / gt_s if gt_s and sc.get('camera_height_prior', {}).get('metres_per_unit') else None, 3)}× (assumed {sc.get('camera_height_prior', {}).get('assumed_camera_height_m')} m);",
              f"  - plan registration {f(ae.get('registration_scale_over_gt_scale'), 4)}×.",
              f"- ATE after Sim3 alignment to GT: final trajectory RMSE {f(ge.get('slam_ate_sim3', {}).get('rmse'), 3)} m, online poses RMSE {f(ge.get('online_ate_sim3', {}).get('rmse'), 3)} m, coverage {f(ge.get('slam_ate_sim3', {}).get('coverage'), 3)}."]
        if dr:
            D += [f"- PanoVGGT dense:",
                  f"  - {dr.get('keyframes_ok')}/{dr.get('keyframes')} keyframes, {dr.get('points')} points;",
                  f"  - {f(dr.get('inference_s'), 0)} s inference, peak GPU {f(dr.get('peak_torch_gpu_mb'), 0)} MB;",
                  f"  - depth vs SLAM landmark ranges: {f(dr.get('depth_rel_err_median_inliers'), 3)} median relative error (inliers), {f(dr.get('depth_rel_err_median_all'), 3)} (all);",
                  f"  - PanoVGGT scale spread across windows {f(dr.get('scale_rel_spread_across_keyframes'), 2)}."]
        c = al.get("confidence", {})
        g_only = ae.get("plan_frame_2d_error_global_transform_only", {})
        D += ["", "### Floor-plan alignment (automatic, no manual correspondences)", "",
              f"- Selected evidence: {al.get('selected_evidence')}.",
              f"- Status **{c.get('status')}**: wall inliers {f(c.get('wall_inlier_frac'))}, margin to best distinct alternative {f(c.get('margin'))}, {c.get('n_wall_cells')} wall cells.",
              "- Variant GT ablation (selection never sees GT):",
              *[f"  - {vn}: {vv_.get('status')}, {vv_.get('n_wall_cells')} wall cells → median {f(vv_.get('median'), 3)} m, RMSE {f(vv_.get('rmse'), 3)} m, max {f(vv_.get('max'), 3)} m"
                for vn, vv_ in (ae.get('variants') or {}).items()],
              f"- 2D error in plan frame, single global similarity: median {f(g_only.get('median'), 3)}, RMSE {f(g_only.get('rmse'), 3)}, max {f(g_only.get('max'), 3)} m.",
              f"- After segment refinement ({sum(1 for s in (al.get('segment_refinement') or []) if s.get('accepted'))}/{len(al.get('segment_refinement') or [])} windows accepted): median {f(refined.get('median'), 3)}, RMSE {f(refined.get('rmse'), 3)}, max {f(refined.get('max'), 3)} m. Coverage {f(refined.get('coverage'), 3)}.",
              f"- Coverage-completed trajectory (flagged fills): coverage {f(filled.get('coverage'), 3)}, median {f(filled.get('median'), 3)} m. Median error by flag {filled.get('median_error_by_flag')}. Hilti score {f(filled.get('hilti_score'), 1)}/100."]
        if dc:
            D += ["", "### As-built vs plan", "", f"- Status: {dc.get('status')}."]
            if dc.get("status") == "ok":
                D += [f"- Planned wall boundary: {dc.get('planned_boundary_length_m')} m.",
                      f"- Confirmed fraction of boundary seen from the path: {f(dc.get('confirmed_fraction_of_seen'))}.",
                      f"- {len(dc.get('observed_not_in_plan_clusters', []))} observed-not-in-plan clusters (candidates only; see `discrepancy/discrepancies.json`)."]
        if loc:
            D += ["", "### Particle-filter localization (causal replay of online SLAM output)", "",
                  "| experiment | init | localized steps | median m | RMSE m | p90 m | <0.5 m | <1 m | yaw ° | converged <1 m at s | recovery after kidnap s |", "|---|---|---|---|---|---|---|---|---|---|---|"]
            for k, r in loc.items():
                e = r.get("evaluation_vs_gt", {})
                D.append(f"| {k} | {r.get('init', {}).get('mode')} | {f(r.get('frac_steps_localized'), pct=True)} | {f(e.get('err_median_m'))} | {f(e.get('err_rmse_m'))} | {f(e.get('err_p90_m'))} | "
                         f"{f(e.get('frac_below_0.5m'), pct=True)} | {f(e.get('frac_below_1m'), pct=True)} | {f(e.get('yaw_err_median_deg'), 1)} | {f(e.get('converged_below_1m_at_s'), 1)} | {f(e.get('recovery_time_after_kidnap_s'), 1)} |")
            D.append("\nErrors are computed only over GT poses where the filter reports an estimate: not while SLAM is lost, and not before a global initialisation.")
        if ob:
            D += ["", "### Objects", "",
                  f"- {ob.get('n_objects')} objects from {ob.get('n_observations')} observations over {ob.get('keyframes_processed')} keyframes × {ob.get('views_per_keyframe')} views; inference {f(ob.get('inference_s'), 1)} s.",
                  f"- Status: {ob.get('n_confirmed_static')} confirmed static, {ob.get('n_tentative')} tentative, {ob.get('n_dynamic')} dynamic. {ob.get('n_camera_rigid_observations_removed')} camera-rigid observations removed.",
                  f"- 3D from: {ob.get('obs_geometry_source')}.",
                  f"- Centroid re-projection inside its detections: {f(ob.get('centroid_reprojection_inside_detection_frac'), pct=True)}.",
                  f"- Duplicate candidates: {ob.get('duplicate_candidates_same_label_within_gate_never_coobserved')}. Label conflicts: {ob.get('label_conflict_objects')}.",
                  f"- Per class: {ob.get('per_class')}.",
                  "- No object ground truth exists, so these are consistency diagnostics, not accuracy."]
        if vv:
            pb = vv.get("playback", {})
            D += ["", "### Viewer validation (Playwright + Chromium, `scripts/validate_viewer.py`)", "",
                  f"- Renderer: {vv.get('webgl_renderer')}. All checks passed: {f(vv.get('all_passed'))}. Checks: {vv.get('checks')}.",
                  f"- Render {f(pb.get('render_fps_median'), 0)} fps median (min {f(pb.get('render_fps_min'), 0)}). Playback {f(pb.get('video_fps_effective'), 2)} fps effective. Video↔pose sync max {f(pb.get('pose_sync_ms_max'), 1)} ms. Seek {f(vv.get('seek_latency_ms'), 1)} ms."]
        details += D + [""]
    out = ROOT / "docs/RESULTS.md"
    out.write_text("\n".join(L + [""] + details) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    runs = [Path(a).resolve() for a in sys.argv[1:]] or [ROOT / "outputs" / n for n in ROLES if (ROOT / "outputs" / n).exists()]
    main(runs)
