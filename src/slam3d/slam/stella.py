"""stella_vslam backend (equirectangular monocular SLAM) run in a Docker container.

The upstream library is built unmodified (docker/stella/Dockerfile). slam3d's driver
(cpp/stella_driver) is compiled against it and writes online poses, causal local observations and
the final optimised map. Scale of the result is ARBITRARY (monocular).
"""
from __future__ import annotations

import os
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import yaml

from slam3d.geometry.transforms import quat_to_R

IMAGE = "slam3d-stella:e445b54"
REPO = Path(__file__).resolve().parents[3]
DRIVER_BUILD = REPO / "cpp/stella_driver/build"
DRIVER_BIN = DRIVER_BUILD / "slam3d_stella_driver"


def make_config(width: int, height: int, fps: float, out_path: Path, overrides: dict | None = None) -> dict:
    cfg = {
        "Camera": {"name": "equirectangular 360", "setup": "monocular", "model": "equirectangular",
                   "fps": float(fps), "cols": int(width), "rows": int(height), "color_order": "BGR"},
        "Preprocessing": {"min_size": 800},
        "Feature": {"name": "ORB", "scale_factor": 1.2, "num_levels": 8,
                    "ini_fast_threshold": 20, "min_fast_threshold": 7},
        "Mapping": {"backend": "g2o", "baseline_dist_thr_ratio": 0.02, "redundant_obs_ratio_thr": 0.95,
                    "num_covisibilities_for_landmark_generation": 20,
                    "num_covisibilities_for_landmark_fusion": 20, "residual_deg_thr": 0.4},
        "Tracking": {"backend": "g2o"},
        "LoopDetector": {"backend": "g2o", "enabled": True, "reject_by_graph_distance": True,
                         "min_distance_on_graph": 50},
        "GraphOptimizer": {"min_num_shared_lms": 200},
        "GlobalOptimizer": {"thr_neighbor_keyframes": 100},
        "System": {"map_format": "msgpack", "num_grid_cols": 96, "num_grid_rows": 48},
    }
    for sec, vals in (overrides or {}).items():
        cfg.setdefault(sec, {}).update(vals)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("# generated by slam3d\n" + yaml.safe_dump(cfg, sort_keys=False))
    return cfg


def _docker(cmd: str, log_path: Path | None = None, name: str | None = None):
    uid, gid = os.getuid(), os.getgid()
    home = str(Path.home())
    args = ["docker", "run", "--rm", "--user", f"{uid}:{gid}", "-v", f"{home}:{home}", "-w", str(REPO)]
    if name:
        args += ["--name", name]
    args += [IMAGE, "bash", "-lc", cmd]
    if log_path:
        with open(log_path, "w") as lf:
            return subprocess.run(args, stdout=lf, stderr=subprocess.STDOUT)
    return subprocess.run(args)


def build_driver(log_path: Path | None = None) -> Path:
    DRIVER_BUILD.mkdir(parents=True, exist_ok=True)
    r = _docker(f"cd {DRIVER_BUILD} && cmake -DSTELLA_SRC_DIR=/stella_vslam .. && make -j8", log_path)
    if r.returncode != 0 or not DRIVER_BIN.exists():
        raise RuntimeError(f"driver build failed, see {log_path}")
    return DRIVER_BIN


def run(frames_csv: Path, out_dir: Path, config_yaml: Path, vocab: Path, mask: Path | None = None,
        obs_every: int = 3, max_frames: int | None = None, log_path: Path | None = None,
        container_name: str | None = None) -> int:
    if not DRIVER_BIN.exists():
        build_driver(out_dir / "driver_build.log")
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = (f"{DRIVER_BIN} --vocab {vocab} --config {config_yaml} --frames {frames_csv} --out {out_dir} "
           f"--obs-every {obs_every}")
    if mask:
        cmd += f" --mask {mask}"
    if max_frames:
        cmd += f" --max-frames {max_frames}"
    return _docker(cmd, log_path, name=container_name).returncode


