@dataclass
class OnlinePoses:
    idx: np.ndarray
    t: np.ndarray
    state: np.ndarray  # str
    loop_ba: np.ndarray  # bool
    n_tracked: np.ndarray
    track_ms: np.ndarray
    T: np.ndarray  # (N,4,4) T_world_cam, NaN when lost
    valid: np.ndarray


def load_online_poses(path) -> OnlinePoses:
    idx, t, st, lb, nt, ms, vals = [], [], [], [], [], [], []
    with open(path) as f:
        for line in f:
            if line.startswith("#"):
                continue
            p = line.split()
            if len(p) < 13:
                continue
            idx.append(int(p[0])); t.append(float(p[1])); st.append(p[2]); lb.append(p[3] == "1")
            nt.append(int(p[4])); ms.append(float(p[5])); vals.append([float(x) for x in p[6:13]])
    v = np.asarray(vals, float).reshape(-1, 7)
    valid = np.isfinite(v).all(1)
    T = np.full((len(v), 4, 4), np.nan)
    if valid.any():
        T[valid] = np.eye(4)
        T[valid, :3, :3] = quat_to_R(v[valid, 3:7])
        T[valid, :3, 3] = v[valid, :3]
    return OnlinePoses(np.array(idx), np.array(t), np.array(st), np.array(lb), np.array(nt), np.array(ms), T, valid)


def load_local_obs(path):
    """Returns list of (frame_idx, t, landmark_ids (n,), points_cam (n,3))."""
    data = Path(path).read_bytes()
    out, off = [], 0
    rec = np.dtype([("id", "<u4"), ("p", "<f4", 3)])
    while off + 16 <= len(data):
        idx = int(np.frombuffer(data, "<i4", 1, off)[0]); off += 4
        t = float(np.frombuffer(data, "<f8", 1, off)[0]); off += 8
        n = int(np.frombuffer(data, "<i4", 1, off)[0]); off += 4
        arr = np.frombuffer(data, rec, n, off); off += n * rec.itemsize
        out.append((idx, t, arr["id"].copy(), arr["p"].astype(np.float64)))
    return out


def load_landmarks(path):
    rec = np.dtype([("id", "<u4"), ("p", "<f4", 3), ("nobs", "<u4"), ("first_kf", "<u4")])
    a = np.fromfile(path, rec)
    return {"id": a["id"], "xyz": a["p"].astype(np.float64), "nobs": a["nobs"], "first_kf": a["first_kf"]}


def load_keyframes(path):
    a = np.genfromtxt(path, delimiter=",", skip_header=1).reshape(-1, 14)
    T = np.tile(np.eye(4), (len(a), 1, 1))
    T[:, :3, :3] = a[:, 2:11].reshape(-1, 3, 3)
    T[:, :3, 3] = a[:, 11:14]
    order = np.argsort(a[:, 1])
    return {"id": a[order, 0].astype(int), "t": a[order, 1], "T": T[order]}


def load_kf_obs(path):
    rec = np.dtype([("kf", "<u4"), ("lm", "<u4"), ("uv", "<f4", 2)])
    return np.fromfile(path, rec)
